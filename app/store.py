"""Single-process durable TTS jobs and content cache. No external queue broker."""
from __future__ import annotations

import fcntl
import hashlib
import json
import os
import shutil
import sqlite3
import time
from pathlib import Path
from uuid import uuid4

ACTIVE = ("preparing", "queued", "running", "assembling")
TERMINAL = ("completed", "failed", "cancelled", "expired")


class JobError(ValueError):
    def __init__(self, code, message, status=400):
        self.code, self.status = code, status
        super().__init__(message)


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode()).hexdigest()


def file_hash(path):
    value = hashlib.sha256()
    with Path(path).open("rb") as source:
        while block := source.read(1024 * 1024):
            value.update(block)
    return value.hexdigest()


def atomic_text(path, text):
    path = Path(path)
    temporary = path.with_name(path.name + ".tmp")
    try:
        with temporary.open("w", encoding="utf-8") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


class Store:
    def __init__(self, settings):
        self.settings = settings
        self.root = settings.state_path.resolve()
        self.root.mkdir(parents=True, exist_ok=True, mode=0o700)
        self.jobs = self.root / "jobs"
        self.cache = self.root / "cache"
        self.jobs.mkdir(exist_ok=True, mode=0o700)
        self.cache.mkdir(exist_ok=True, mode=0o700)
        self.lock = (self.root / "worker.lock").open("a")
        try:
            fcntl.flock(self.lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            self.lock.close()
            raise RuntimeError("TTS state already has a worker; run one Uvicorn worker") from None
        self.db = sqlite3.connect(self.root / "tts.sqlite3", timeout=10)
        self.db.row_factory = sqlite3.Row
        if self.db.execute("PRAGMA user_version").fetchone()[0] not in {0, 1}:
            self.db.close()
            self.lock.close()
            raise RuntimeError("Unsupported TTS state schema")
        self.db.executescript("""
PRAGMA journal_mode=WAL;
PRAGMA synchronous=FULL;
PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS jobs (
 id TEXT PRIMARY KEY, owner TEXT NOT NULL, request_hash TEXT NOT NULL, idempotency TEXT,
 state TEXT NOT NULL, options TEXT NOT NULL, durable INTEGER NOT NULL, characters INTEGER NOT NULL,
 source_bytes INTEGER NOT NULL, prepared_offset INTEGER NOT NULL DEFAULT 0,
 normalized_bytes INTEGER NOT NULL DEFAULT 0, reserved_bytes INTEGER NOT NULL DEFAULT 0,
 total INTEGER NOT NULL DEFAULT 0, done INTEGER NOT NULL DEFAULT 0, cached INTEGER NOT NULL DEFAULT 0,
 report TEXT NOT NULL DEFAULT '{}', error TEXT, result TEXT,
 created REAL NOT NULL, updated REAL NOT NULL, served REAL NOT NULL,
 UNIQUE(owner,idempotency)
);
CREATE INDEX IF NOT EXISTS jobs_ready ON jobs(state,served);
CREATE INDEX IF NOT EXISTS jobs_hash ON jobs(owner,request_hash);
CREATE TABLE IF NOT EXISTS chunks (
 job_id TEXT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE, n INTEGER NOT NULL,
 text TEXT NOT NULL, cache_key TEXT NOT NULL, frames INTEGER, PRIMARY KEY(job_id,n)
);
CREATE INDEX IF NOT EXISTS chunks_cache ON chunks(cache_key);
CREATE TABLE IF NOT EXISTS cache (
 key TEXT PRIMARY KEY, frames INTEGER NOT NULL, bytes INTEGER NOT NULL, sha256 TEXT NOT NULL, used REAL NOT NULL
);
PRAGMA user_version=1;
""")
        self.db.commit()
        self.db.execute("UPDATE jobs SET state='cancelled',error=? WHERE durable=0 AND state IN ('preparing','queued','running','assembling')", (json.dumps({"code": "client_disconnected", "message": "Synchronous caller disconnected during restart"}),))
        self.db.execute("UPDATE jobs SET state='queued',reserved_bytes=0 WHERE state IN ('running','assembling')")
        self.db.commit()
        self.last_cleanup = 0
        self.cleanup()

    def close(self):
        self.db.close()
        self.lock.close()

    def row(self, identifier, owner=None):
        if not isinstance(identifier, str) or not identifier.startswith("tts_") or len(identifier) != 36:
            raise JobError("not_found", "Job not found", 404)
        row = self.db.execute("SELECT * FROM jobs WHERE id=?" + (" AND owner=?" if owner is not None else ""), (identifier, owner) if owner is not None else (identifier,)).fetchone()
        if not row:
            raise JobError("not_found", "Job not found", 404)
        return dict(row)

    def directory(self, identifier):
        # ID is generated by this service; never use arbitrary user input as a path.
        self.row(identifier)
        return self.jobs / identifier

    def submit(self, owner, request, text, max_bytes, idempotency=None, durable=True):
        if idempotency is not None and (not re_key(idempotency)):
            raise JobError("invalid_idempotency", "Idempotency-Key must contain 1–200 visible ASCII characters")
        options = {**request, "max_output_bytes": max_bytes, "_source_sha256": hashlib.sha256(text.encode()).hexdigest(), "_lexicon_sha256": digest(request.get("lexicon", {}))}
        request_hash = digest([options, text])
        if idempotency:
            existing = self.db.execute("SELECT * FROM jobs WHERE owner=? AND idempotency=?", (owner, idempotency)).fetchone()
            if existing:
                intent = lambda opts: {k: v for k, v in opts.items() if k not in {"_engine", "_normalizer", "_render", "lexicon"}}
                if intent(json.loads(existing["options"])) != intent(options):
                    raise JobError("idempotency_conflict", "Idempotency-Key already belongs to different input or parameters", 409)
                return dict(existing)
        existing = self.db.execute("SELECT * FROM jobs WHERE owner=? AND request_hash=? AND state IN ('preparing','queued','running','assembling','completed') ORDER BY created DESC LIMIT 1", (owner, request_hash)).fetchone()
        if existing and not idempotency:
            return dict(existing)
        pending = self.db.execute("SELECT count(*),coalesce(sum(characters),0) FROM jobs WHERE state IN ('preparing','queued','running','assembling')").fetchone()
        own = self.db.execute("SELECT count(*) FROM jobs WHERE owner=? AND state IN ('preparing','queued','running','assembling')", (owner,)).fetchone()[0]
        if pending[0] >= self.settings.max_pending or own >= max(2, self.settings.max_pending // 2) or pending[1] + len(text) > self.settings.max_queued_chars:
            raise JobError("queue_full", "Speech queue is full; retry later with the same Idempotency-Key", 429)
        self.ensure_space(len(text.encode()) * 3)
        identifier = "tts_" + uuid4().hex
        directory = self.jobs / identifier
        directory.mkdir(mode=0o700)
        now = time.time()
        try:
            atomic_text(directory / "source.txt", text)
            self.db.execute("INSERT INTO jobs(id,owner,request_hash,idempotency,state,options,durable,characters,source_bytes,created,updated,served) VALUES(?,?,?,?,?,?,?,?,?,?,?,?)", (identifier, owner, request_hash, idempotency, "preparing", json.dumps(options, ensure_ascii=False), int(durable), len(text), (directory / "source.txt").stat().st_size, now, now, now))
            self.db.commit()
        except BaseException:
            shutil.rmtree(directory)
            raise
        return self.row(identifier)

    def update(self, identifier, **values):
        values["updated"] = time.time()
        self.db.execute("UPDATE jobs SET " + ",".join(f"{name}=?" for name in values) + " WHERE id=?", (*values.values(), identifier))
        self.db.commit()

    def next(self):
        row = self.db.execute("SELECT * FROM jobs WHERE state IN ('preparing','queued','running') AND (state='preparing' OR done<total) ORDER BY served,created LIMIT 1").fetchone()
        return dict(row) if row else None

    def ready(self, short=True, seconds=300):
        compare = "<=" if short else ">"
        row = self.db.execute(f"SELECT * FROM jobs WHERE state IN ('queued','running') AND total>0 AND done=total AND coalesce((SELECT sum(frames) FROM chunks WHERE job_id=jobs.id),0) {compare} ? * json_extract(options,'$.speed') ORDER BY served,created LIMIT 1", (seconds * self.settings.sample_rate,)).fetchone()
        return dict(row) if row else None

    def prepared(self, identifier, offset, chunks, report, final, normalized_bytes=0):
        row = self.row(identifier)
        if row["state"] != "preparing":
            return
        previous = json.loads(row["report"])
        combined = {"version": report["version"], "source_characters": previous.get("source_characters", 0) + report["source_characters"], "normalized_characters": previous.get("normalized_characters", 0) + report["normalized_characters"], "changed": previous.get("changed", False) or report["changed"], "warnings": [*previous.get("warnings", []), *report["warnings"]][:30]}
        with self.db:
            self.db.executemany("INSERT INTO chunks(job_id,n,text,cache_key) VALUES(?,?,?,?)", [(identifier, row["total"] + n, text, fingerprint) for n, (text, fingerprint) in enumerate(chunks)])
            self.db.execute("UPDATE jobs SET total=total+?,prepared_offset=?,normalized_bytes=normalized_bytes+?,report=?,state=?,served=?,updated=? WHERE id=?", (len(chunks), offset, normalized_bytes, json.dumps(combined), "queued" if final else "preparing", time.time(), time.time(), identifier))

    def next_chunk(self, identifier):
        row = self.db.execute("SELECT * FROM chunks WHERE job_id=? AND frames IS NULL ORDER BY n LIMIT 1", (identifier,)).fetchone()
        return dict(row) if row else None

    def cached(self, fingerprint):
        row = self.db.execute("SELECT * FROM cache WHERE key=?", (fingerprint,)).fetchone()
        path = self.cache / (fingerprint + ".flac")
        if row:
            if path.is_file() and path.stat().st_size == row["bytes"] and file_hash(path) == row["sha256"]:
                self.db.execute("UPDATE cache SET used=? WHERE key=?", (time.time(), fingerprint))
                self.db.commit()
                return row["frames"]
        # Corrupt or evicted parts are regenerated individually, including other job references.
        with self.db:
            affected = self.db.execute("SELECT DISTINCT job_id FROM chunks WHERE cache_key=? AND frames IS NOT NULL AND job_id IN (SELECT id FROM jobs WHERE state NOT IN ('completed','expired'))", (fingerprint,)).fetchall()
            self.db.execute("UPDATE chunks SET frames=NULL WHERE cache_key=? AND job_id IN (SELECT id FROM jobs WHERE state NOT IN ('completed','expired'))", (fingerprint,))
            self.db.execute("DELETE FROM cache WHERE key=?", (fingerprint,))
            for item in affected:
                self.db.execute("UPDATE jobs SET done=(SELECT count(*) FROM chunks WHERE job_id=jobs.id AND frames IS NOT NULL) WHERE id=?", (item[0],))
        path.unlink(missing_ok=True)
        return None

    def chunk_done(self, job, chunk, frames, was_cached):
        path = self.cache / (chunk["cache_key"] + ".flac")
        with self.db:
            self.db.execute("INSERT OR REPLACE INTO cache VALUES(?,?,?,?,?)", (chunk["cache_key"], frames, path.stat().st_size, file_hash(path), time.time()))
            if self.row(job["id"])["state"] not in ACTIVE:
                return
            self.db.execute("UPDATE chunks SET frames=? WHERE job_id=? AND n=?", (frames, job["id"], chunk["n"]))
            self.db.execute("UPDATE jobs SET state='queued',done=done+1,cached=cached+?,served=?,updated=? WHERE id=?", (int(was_cached), time.time(), time.time(), job["id"]))

    def resume(self, identifier, owner):
        job = self.row(identifier, owner)
        if job["state"] == "completed":
            metadata = json.loads(job["result"])
            path = self.directory(identifier) / ("result." + metadata["extension"])
            if not path.is_file() or path.stat().st_size != metadata["bytes"] or file_hash(path) != metadata["sha256"]:
                self.update(identifier, state="failed", result=None)
                job = self.row(identifier, owner)
        if job["state"] == "expired":
            raise JobError("expired", "Job artifacts expired; submit the source again", 410)
        if job["state"] not in {"failed", "cancelled"}:
            return job
        for row in self.db.execute("SELECT cache_key FROM chunks WHERE job_id=? AND frames IS NOT NULL", (identifier,)).fetchall():
            self.cached(row[0])
        state = "queued" if job["prepared_offset"] >= job["source_bytes"] else "preparing"
        self.update(identifier, state=state, error=None, served=time.time(), durable=1)
        return self.row(identifier)

    def fail(self, identifier, error):
        if self.row(identifier)["state"] in ACTIVE:
            self.update(identifier, state="failed", error=json.dumps(error), reserved_bytes=0)

    def view(self, job):
        result = {"id": job["id"], "state": job["state"], "created_at": job["created"], "updated_at": job["updated"], "progress": {"characters": job["characters"], "prepared_bytes": job["prepared_offset"], "source_bytes": job["source_bytes"], "segments": job["total"], "completed_segments": job["done"], "cached_segments": job["cached"]}, "normalization": json.loads(job["report"]), "error": json.loads(job["error"]) if job["error"] else None}
        if job["result"]:
            result["result"] = json.loads(job["result"])
        options = json.loads(job["options"])
        result["request"] = {k: v for k, v in options.items() if not k.startswith("_") and k != "lexicon"}
        if options.get("_engine"):
            engine = options["_engine"]
            result["processing"] = {"model_sha256": engine[0], "sample_rate": engine[1], "intensity": engine[2], "peak_ceiling": engine[3], "normalization": options.get("_normalizer"), "lexicon_sha256": options.get("_lexicon_sha256")}
            if options.get("_render"):
                result["processing"].update(silence_seconds=options["_render"][0], opus_bitrate=options["_render"][1])
        result["links"] = {name: f"/v1/audio/jobs/{job['id']}/{name}" for name in ("result", "source", "normalized", "segments")}
        return result

    def ensure_space(self, required=1024 * 1024):
        used = self.db.execute("SELECT coalesce(sum(bytes),0) FROM cache").fetchone()[0]
        used += self.db.execute("SELECT coalesce(sum(source_bytes + normalized_bytes*3 + reserved_bytes + coalesce(json_extract(result,'$.bytes'),0)),0) FROM jobs WHERE state<>'expired'").fetchone()[0]
        if used + required > self.settings.state_max_bytes:
            self.cleanup(force=True)
            used = self.db.execute("SELECT coalesce(sum(bytes),0) FROM cache").fetchone()[0] + self.db.execute("SELECT coalesce(sum(source_bytes + normalized_bytes*3 + reserved_bytes + coalesce(json_extract(result,'$.bytes'),0)),0) FROM jobs WHERE state<>'expired'").fetchone()[0]
        if used + required > self.settings.state_max_bytes or shutil.disk_usage(self.root).free < required + 64 * 1024**2:
            raise JobError("storage_limit", "Speech storage budget is exhausted; free space or increase the configured budget, then resume", 507)

    def expire(self, identifier):
        options = json.loads(self.row(identifier)["options"])
        intent = {k: v for k, v in options.items() if k not in {"lexicon", "_engine", "_normalizer", "_render"}}
        shutil.rmtree(self.jobs / identifier, ignore_errors=False) if (self.jobs / identifier).exists() else None
        with self.db:
            self.db.execute("UPDATE jobs SET state='expired',result=NULL,report='{}',source_bytes=0,normalized_bytes=0,reserved_bytes=0,options=? WHERE id=?", (json.dumps(intent), identifier))
            self.db.execute("DELETE FROM chunks WHERE job_id=?", (identifier,))

    def cleanup(self, force=False):
        now = time.time()
        if not force and now - self.last_cleanup < 60:
            return
        self.last_cleanup = now
        cutoff = now - self.settings.retention_seconds
        for job in self.db.execute("SELECT id FROM jobs WHERE state IN ('completed','failed','cancelled') AND updated<?", (cutoff,)).fetchall():
            self.expire(job["id"])
        total = self.db.execute("SELECT coalesce(sum(bytes),0) FROM cache").fetchone()[0]
        candidates = self.db.execute("SELECT * FROM cache c WHERE NOT EXISTS(SELECT 1 FROM chunks ch JOIN jobs j ON j.id=ch.job_id WHERE ch.cache_key=c.key AND j.state IN ('preparing','queued','running','assembling')) ORDER BY used").fetchall()
        for row in candidates:
            if row["used"] >= cutoff and total <= self.settings.cache_max_bytes:
                continue
            (self.cache / (row["key"] + ".flac")).unlink(missing_ok=True)
            self.db.execute("DELETE FROM cache WHERE key=?", (row["key"],))
            total -= row["bytes"]
        retained = self.db.execute("SELECT coalesce(sum(coalesce(json_extract(result,'$.bytes'),0)),0) FROM jobs WHERE state='completed'").fetchone()[0]
        for row in self.db.execute("SELECT id,result FROM jobs WHERE state='completed' AND updated<? ORDER BY updated", (now - 300,)).fetchall():
            if retained + total <= self.settings.cache_max_bytes:
                break
            retained -= json.loads(row["result"])["bytes"]
            self.expire(row["id"])
        self.db.execute("DELETE FROM jobs WHERE state='expired' AND updated<?", (now - self.settings.retention_seconds * 2,))
        self.db.commit()


def re_key(value):
    return isinstance(value, str) and 1 <= len(value) <= 200 and all(33 <= ord(c) <= 126 for c in value)
